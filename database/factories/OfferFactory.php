        return [
            'supplier_id' => Supplier::factory(),
            'import_id' => Import::factory(),
            'property_id' => Property::factory(),
            'external_id' => fake()->unique()->slug(3),
            'check_in' => '2026-10-10',
            'check_out' => '2026-10-15',
            'max_guests' => 4,
            'price' => 72500,
            'currency' => 'EUR',
            'available_units' => 2,
            'expires_at' => now()->addDay(),
        ];
    }
}
